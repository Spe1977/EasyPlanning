    val javaLocale: Locale
        get() = if (language == AppLanguage.ITALIAN) Locale.ITALIAN else Locale.ENGLISH

    fun reminderText(option: ReminderOption): String = when (option) {
        ReminderOption.NONE -> if (language == AppLanguage.ITALIAN) "Nessuno" else "None"
        ReminderOption.AT_START -> if (language == AppLanguage.ITALIAN) "All'inizio" else "At start"
        ReminderOption.MIN_15 -> if (language == AppLanguage.ITALIAN) "15 min prima" else "15 min before"
        ReminderOption.MIN_30 -> if (language == AppLanguage.ITALIAN) "30 min prima" else "30 min before"
        ReminderOption.HOUR_1 -> if (language == AppLanguage.ITALIAN) "1 ora prima" else "1 hour before"
        ReminderOption.HOUR_2 -> if (language == AppLanguage.ITALIAN) "2 ore prima" else "2 hours before"
        ReminderOption.DAY_1 -> if (language == AppLanguage.ITALIAN) "1 giorno prima" else "1 day before"
    }

    fun shortWeekday(day: DayOfWeek): String = if (language == AppLanguage.ITALIAN) {
        when (day) {
            DayOfWeek.MONDAY -> "Lun"
            DayOfWeek.TUESDAY -> "Mar"
            DayOfWeek.WEDNESDAY -> "Mer"
            DayOfWeek.THURSDAY -> "Gio"
            DayOfWeek.FRIDAY -> "Ven"
            DayOfWeek.SATURDAY -> "Sab"
            DayOfWeek.SUNDAY -> "Dom"
        }
    } else {
        when (day) {
            DayOfWeek.MONDAY -> "Mon"
            DayOfWeek.TUESDAY -> "Tue"
            DayOfWeek.WEDNESDAY -> "Wed"
            DayOfWeek.THURSDAY -> "Thu"
            DayOfWeek.FRIDAY -> "Fri"
            DayOfWeek.SATURDAY -> "Sat"
            DayOfWeek.SUNDAY -> "Sun"
        }
    }

    private val monthYearFormatter: DateTimeFormatter
        get() = if (language == AppLanguage.ITALIAN) IT_MONTH_YEAR_FMT else EN_MONTH_YEAR_FMT

    private val fullDateFormatter: DateTimeFormatter
        get() = if (language == AppLanguage.ITALIAN) IT_FULL_DATE_FMT else EN_FULL_DATE_FMT

    private val shortDateFormatter: DateTimeFormatter
        get() = if (language == AppLanguage.ITALIAN) IT_SHORT_DATE_FMT else EN_SHORT_DATE_FMT

    private val compactMonthYearFormatter: DateTimeFormatter
        get() = if (language == AppLanguage.ITALIAN) IT_COMPACT_MY_FMT else EN_COMPACT_MY_FMT

    fun formatMonthYear(ym: YearMonth): String =
        ym.format(monthYearFormatter).replaceFirstChar { it.titlecase(javaLocale) }

    fun formatFullDate(date: LocalDate): String =
        date.format(fullDateFormatter).replaceFirstChar { it.titlecase(javaLocale) }

    fun formatShortDate(date: LocalDate): String =
        date.format(shortDateFormatter)

    fun formatCompactMonthYear(date: LocalDate): String =
        date.format(compactMonthYearFormatter).replace(".", "").uppercase(javaLocale)

    fun formatHoursFromMinutes(totalMinutes: Int): String {
        val h = totalMinutes / 60
        val m = totalMinutes % 60
        return if (m == 0) "${h}h" else "${h}h ${m}m"
    }

    fun formatHalfHours(halfHours: Int): String {
        val sep = if (language == AppLanguage.ITALIAN) "," else "."
        val formatted = if (halfHours % 2 == 0) "${halfHours / 2}" else "${halfHours / 2}${sep}5"
        return "${formatted}h"
    }

    companion object {
        private val IT_MONTH_YEAR_FMT: DateTimeFormatter = DateTimeFormatter.ofPattern("MMMM yyyy", Locale.ITALIAN)
        private val EN_MONTH_YEAR_FMT: DateTimeFormatter = DateTimeFormatter.ofPattern("MMMM yyyy", Locale.ENGLISH)
        private val IT_FULL_DATE_FMT: DateTimeFormatter = DateTimeFormatter.ofPattern("EEEE d MMMM yyyy", Locale.ITALIAN)
        private val EN_FULL_DATE_FMT: DateTimeFormatter = DateTimeFormatter.ofPattern("EEEE, MMM d, yyyy", Locale.ENGLISH)
        private val IT_SHORT_DATE_FMT: DateTimeFormatter = DateTimeFormatter.ofPattern("dd/MM/yyyy", Locale.ITALIAN)
        private val EN_SHORT_DATE_FMT: DateTimeFormatter = DateTimeFormatter.ofPattern("MMM d, yyyy", Locale.ENGLISH)
        private val IT_COMPACT_MY_FMT: DateTimeFormatter = DateTimeFormatter.ofPattern("MMM yy", Locale.ITALIAN)
        private val EN_COMPACT_MY_FMT: DateTimeFormatter = DateTimeFormatter.ofPattern("MMM yy", Locale.ENGLISH)
    }
}

